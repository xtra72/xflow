// 게이지가 **폭·높이를 따로 갖는가**를 답하는 한 가지 판정.
//
// 세로바만 사각형이라 "가늘고 길게" 나 "굵고 짧게" 가 뜻을 갖는다. 원형·반원·바늘은
// 비율 자체가 값을 읽는 규약의 일부라(각도로 읽는다) 축을 나누면 그림이 찌그러지면서
// 값을 잘못 읽게 된다 — 그래서 이 판정이 설정 UI(높이 칸을 낼지)와 드래그 레이어
// (손잡이가 축을 나눌지) 양쪽의 갈림길이 된다.
//
// 컴포넌트 파일이 아닌 별도 모듈에 두는 이유는 두 소비처가 서로 다른 파일이기 때문이다
// — 한쪽에 두면 다른 쪽이 컴포넌트 모듈을 값 때문에 import 하게 된다.

/** 폭·높이를 따로 갖는 게이지 유형. */
export function isAxisSplitGauge(config: Record<string, unknown>): boolean {
  return config.gaugeType === 'vertical-bar';
}
