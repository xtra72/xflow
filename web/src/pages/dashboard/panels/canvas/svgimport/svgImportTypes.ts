/**
 * 파싱 **전에** 자르는 입력 바이트 상한.
 *
 * 파싱 뒤로 옮기면 내부 엔티티 확장 폭탄(`<!ENTITY a "AAAA">` 를 겹쳐 쓰는 문서)이
 * 먼저 터진다 — 브라우저가 그것을 막는다고 알려져 있으나 본 SPEC 은 그것을 **실측하지
 * 않았다**(가정 A8). 실측하지 않은 방어에 기대지 않는 유일한 길이 파싱 전에 자르는
 * 것이다(위험 R10).
 *
 * 2 MiB 인 이유: 실사용 SVG 아이콘·도면은 수십~수백 KB이고, 그 열 배 이상을 남겨도
 * 파싱 시간이 눈에 띄지 않는다.
 */
export const MAX_IMPORT_FILE_BYTES = 2 * 1024 * 1024;

/**
 * 한 번의 가져오기가 만들 수 있는 요소 수의 상한.
 *
 * 넘으면 **거절한다 — 앞의 것만 가져오지 않는다.** 도구가 내는 문서 순서는 배경→전경
 * 이라 앞쪽은 대개 배경 조각들이고, 그 절단은 "설명 없는 틀린 그림" 이다.
 *
 * **64에서 1024로 올렸다(사용자 결정).** 64는 실무 도면에 맞지 않았다 — draw.io 는
 * 라벨 하나를 요소 하나로 내므로 화면 한 장짜리 설정 도면도 60을 넘고, 넘으면 통째로
 * 거절이라 쓸 수 없었다.
 *
 * **이 수가 무엇을 지키고 있었는지 적어 둔다.** 64는 요소 수 자체가 위험해서가 아니라
 * 대시보드 설정의 256KB 예산을 지키는 **대역**이었다. 이 층(가져오기)에는 바이트를 막는
 * 코드가 없다 — `estimatedBytes` 는 화면에 보여줄 뿐 아무것도 막지 않는다. 그래서 이 수를
 * 올린 지금, **가져오기 안에서** 예산을 지키는 것은 아무것도 없다.
 *
 * **그러나 예산 자체는 허구가 아니다 — 서버가 강제한다.** `internal/api/handler/dashboard.go`
 * 의 `maxDashboardPayloadBytes = 256 * 1024` 가 그것이고, 넘으면 PUT 이 413 Payload Too
 * Large 로 거부되며 **저장되지 않는다**. 즉 예산을 넘긴 결과는 "설정이 조금 커진다" 가
 * 아니라 **"저장이 실패한다"** 이다. (이 파일의 `MAX_IMPORT_TEXT_LENGTH` 머리말이 이미
 * 그 413 을 적고 있었다.)
 *
 * **그래서 지금 일어날 수 있는 일을 실측으로 적는다.**
 * - 사용자 실파일 실측 밀도는 요소당 306 B다(60 요소 · 18,386 B). 그 밀도로는 **약 855
 *   요소**에서 256KB 에 닿는다 — 상한 1024 **아래**다. 즉 현실적인 도면으로도 413 에
 *   닿을 수 있다.
 * - 최악(명령을 가장 적은 경로에 몰고 남은 자리를 256자 한글 문구로 채운 문서)은
 *   **1,578,590 B = 예산의 602%** 다(`svgImportNative.test.ts` §예산 이 실측해 못박는다).
 * - 명령을 한 칸도 쓰지 않는 문구 1024 짜리 문서만으로도 919,470 B(350%)다. 즉
 *   `MAX_IMPORT_COMMANDS` 를 0 으로 두어도 예산은 지켜지지 않는다 — **요소 상한 하나로는
 *   바이트를 죌 수 없다**.
 *
 * 진짜 한도를 세우려면 **바이트로** 세워야 하며(가져오기가 낼 크기를 재서 거절하거나,
 * 저장 전에 막거나), 그것은 이 수를 되돌리는 일이 아니라 **따로 짓는 일**이다.
 *
 * ---
 *
 * **0.8.0 이 그 일을 했다 — 그런데 죄는 방향이 아니라 확보하는 방향으로다(§결정 14).**
 * 사용자가 정한 것은 "상한을 예산에 맞춰 낮춘다" 가 아니라 **"몇 개짜리 도면을 들일지 내가
 * 정하고, 서버가 그만큼의 자리를 확보한다"** 이다. 그래서 위 문단이 적은 어긋남 —
 * 가져오기는 통과하는데 저장이 413 으로 실패한다 — 은 상한을 내려서가 아니라 **예산이 이
 * 수를 따라오게 해서** 닫혔다.
 *
 * **이 상수의 지위가 달라졌다: 이제 이것은 컴파일 *기본값*이다.** 실제로 적용되는 수는
 * 서버 설정 `dashboard.max_canvas_elements` 에서 오고(`GET /dashboard-limits`), 서버는 그
 * 수에 요소당 1 KiB 를 곱해 대시보드 PUT 예산을 잡는다. 1 KiB 를 고른 근거(실측 다섯 중
 * 넷을 덮고 의도적으로 섞은 최악 하나만 거절한다)는 `internal/config/dashboard_budget.go`
 * 가 진다 — 수를 두 곳에 적으면 한 곳이 조용히 틀리므로 여기서 되풀이하지 않는다.
 *
 * **그럼에도 이 수는 남는다.** 서버에 닿지 못한 편집기(오프라인 · 구형 서버 · 권한 없음)가
 * 가져오기를 **못 하게 되는 것**이 상한이 낡는 것보다 나쁘기 때문이다. 그 폴백이
 * `resolveImportLimits` 다.
 */
export const MAX_IMPORT_ELEMENTS = 1024;

/**
 * 한 번의 가져오기가 만들 수 있는 명령 **총수**의 상한.
 *
 * **640에서 10240으로 올렸다(요소 상한과 같은 배 ×16).** 요소 상한만 올리면 이 수가 곧바로
 * 새 죔쇠가 되어 올린 뜻이 거의 사라진다 — 사용자 실파일이 도형 33개로 이미 240 명령을
 * 쓰므로(요소당 약 7), 그보다 2.7배만 큰 도면이면 요소 1024 에는 한참 못 미친 채
 * `tooManyCommands` 로 거절된다. 두 상한의 비를 그대로 둔 것은 그 비가 시험 여럿이 기대는
 * 형상이기도 하기 때문이다(요소당 10 명령에서 두 상한이 **정확히 동시에** 찬다).
 *
 * **이 수는 예산의 죔쇠가 아니다.** 명령을 한 칸도 쓰지 않는 문서(문구 1024 × 256자 한글)
 * 만으로도 919,470 B = 256KB 예산의 350% 이므로, 이 수를 0 으로 두어도 예산은 지켜지지
 * 않는다. 예산을 지키는 일은 요소 상한 머리말에 적은 대로 **바이트로 따로 지어야** 한다.
 * 이 수가 실제로 죄는 것은 아래 둘이다 — 저장 크기의 **일부**, 그리고 포인터 사건당 비용.
 *
 * **최악은 실측이다**(문서 → 계획 → 요소를 실제로 지나 `JSON.stringify` 의 UTF-8 바이트를
 * 잰 값). 손으로 센 수를 그대로 두지 않는 이유는 이 파일이 이미 적은 그것이다 — 상수는
 * 형상이 바뀌는 날 조용히 틀린다. **상한을 64/640 에서 1024/10240 으로 올린 날이 바로 그
 * "형상이 바뀌는 날" 이었으므로 표 전체를 다시 쟀다** — 옛 수를 16배 해서 적지 않았다
 * (측정: `svgImportNative.test.ts` §예산 — 그 시험이 이 표의 수를 `toBe` 로 못박는다).
 * ```
 * 경로 1024개 × 10 명령(명령 10240 전부)      =   807,854 B = 308.17%
 * 문구 1024개 × 256자 한글                    =   919,470 B = 350.75%
 * 원시형 1024개(사각 — 칠과 선을 둘 다 말함)  =   153,518 B =  58.56%
 * 경로 40개(명령 10240 전부) + 원시형 984개   =   842,558 B = 321.41%
 * **최악** 경로 40개(명령 10240 전부) + 문구 984개(256자 한글)
 *                                             = 1,578,590 B = 602.18%
 * ```
 * 마지막 줄이 최악인 이유가 두 상한의 관계를 드러내며, **그 구조는 상한을 올린 뒤에도
 * 그대로다**: 명령을 **가장 적은 경로에 몰면** 요소 자리가 남고, 남은 자리를 글자로 채울 수
 * 있다. 달라진 것은 몰 경로가 3 에서 40 으로, 채울 자리가 61 에서 984 로 는 것뿐이다.
 * (그 관계가 상한의 비가 바뀌어도 살아남는지는 미리 알 수 없어 **다시 재서** 확인했다.)
 *
 * **다섯 중 넷이 예산을 넘는다.** 옛 상한에서는 최악조차 37.46% 로 예산 안이었다. 지금은
 * 최악이 예산의 여섯 배이며, 그런 config 는 PUT 에서 413 을 받아 저장되지 않는다. 그래도
 * **적어 둔다**: 예산이 무엇으로 차는지를 모른 채 상한을 다시 정하는 것이 가장 나쁘다
 * (위험 R6).
 *
 * **원시형은 최악을 갱신하지 못한다** — 명령을 한 칸도 먹지 않으므로 "명령을 몰고 남은
 * 자리를 채운다" 는 그 전략의 **채울 것**에 끼지만, 요소 한 건이 256자 한글 문구의 1/6 에
 * 불과해 남은 자리를 원시형으로 채우면 예산이 오히려 줄어든다(위 넷째 줄).
 *
 * **이 수가 죄는 것은 저장 크기만이 아니다.** 빗나간 클릭 한 번이 모든 경로 요소를
 * 평탄화하므로(`hitTest` 가 처음 맞는 것에서 멈춘다 — 실측), 명령 총수는 포인터 사건당
 * 비용의 상한이기도 하다. 그 아래를 받쳐 줄 두 번째 죔쇠(공간 색인·캐시)가 이 저장소에
 * 없다(위험 R5). **이 축의 비용도 16배가 되었다** — 예산과 달리 이쪽은 이 수가 유일한
 * 죔쇠이므로, 느려지면 줄일 곳은 여기다.
 */
export const MAX_IMPORT_COMMANDS = 10240;

/**
 * 요소 하나당 명령 자리 — 두 상한의 **비**다.
 *
 * **명령 상한이 요소 상한을 따라가기로 한다(§결정 14).** 요소 수만 설정에서 오게 하고 명령
 * 상한을 10240 에 고정하면, 상한을 올린 운영자가 얻는 것이 거의 없다 — 0.7.0 ② 가 이미
 * 잰 그대로다. 사용자 실파일이 도형당 약 7.3 명령을 쓰므로, 요소 2048 을 설정해도 문서는
 * 요소 상한에 한참 못 미친 채 `tooManyCommands` 로 거절된다. **올린 뜻이 사라지는 그
 * 실패를 두 번 겪지 않는다.**
 *
 * 그래서 명령 상한은 `설정된 요소 수 × COMMANDS_PER_ELEMENT` 로 유도된다.
 *
 * 10 인 이유는 새로 고른 것이 아니라 **오늘의 비를 그대로 옮긴 것**이다(10240 ÷ 1024). 그
 * 지점은 요소 상한과 명령 상한이 **정확히 동시에 차는 자리**이고, 경계 시험 여럿이 그
 * 형상 위에 서 있다. 비를 바꿀 근거가 실측에 없으므로 바꾸지 않는다.
 *
 * **0.7.0 이 두 상한을 각각 ×16 으로 올린 것과 이 비(10)를 혼동하지 않는다** — 앞의 것은
 * 64→1024 · 640→10240 이라는 **올린 배수**이고, 이 상수는 **두 상한 사이의 비**다. 두 수가
 * 다르다는 사실이 이 주석에 적혀 있어야 하는 이유는, 실제로 한 번 틀렸기 때문이다.
 *
 * **서버는 이 수를 모른다.** 명령은 SVG 를 읽는 층의 개념이고 서버가 아는 것은 요소 수와
 * 바이트뿐이므로, 오가는 수를 하나로 줄이고 비는 여기서 곱한다.
 */
export const COMMANDS_PER_ELEMENT = MAX_IMPORT_COMMANDS / MAX_IMPORT_ELEMENTS;

/**
 * 한 번의 가져오기에 적용되는 상한 한 쌍. **둘은 언제나 함께 정해진다** — 요소 수 하나에서
 * 명령 수가 유도되므로 따로 실어 나르면 어긋난 조합이 만들어질 수 있다.
 */
export interface SvgImportLimits {
  readonly maxElements: number;
  readonly maxCommands: number;
}

/** 서버에 닿지 못했을 때 서는 값 — 이 모듈의 컴파일 상수 그대로. */
export const DEFAULT_IMPORT_LIMITS: SvgImportLimits = {
  maxElements: MAX_IMPORT_ELEMENTS,
  maxCommands: MAX_IMPORT_COMMANDS,
};

/**
 * 서버가 말한 요소 수를 상한 한 쌍으로 푼다.
 *
 * **쓸 수 없는 값은 전부 기본값으로 떨어진다** — `undefined`(못 물어봤다) · 0 이하 · 정수가
 * 아닌 것 · `NaN`. 거절하지 않고 떨어지는 이유는 하나다: 서버가 이상한 수를 말했다고
 * **가져오기 자체가 서지 않으면**, 사용자는 고칠 수 없는 자리에서 막힌다. 낡은 상한으로
 * 동작하는 편이 못 쓰는 것보다 낫다.
 *
 * 천장을 여기서 다시 두지 않는다 — 서버가 이미 죄어서 보낸다(`ClampMaxCanvasElements`).
 * 두 곳에서 죄면 두 수가 갈라지고, 갈라진 뒤에 이기는 쪽은 **더 작은 쪽**이라 화면이
 * 말하는 상한과 저장이 받는 크기가 어긋난다.
 */
export function resolveImportLimits(maxElements: number | undefined): SvgImportLimits {
  if (maxElements === undefined || !Number.isInteger(maxElements) || maxElements <= 0) {
    return DEFAULT_IMPORT_LIMITS;
  }
  return { maxElements, maxCommands: maxElements * COMMANDS_PER_ELEMENT };
}

/**
 * 문구 요소 하나가 실을 수 있는 **글자 수**의 상한.
 *
 * 명령 상한이 죄지 못하는 축이 이것이다 — 문구 요소는 명령을 하나도 나르지 않으므로
 * `MAX_IMPORT_COMMANDS` 아래를 자유롭게 지나가고, 그동안 제 문자열로 예산을 먹는다.
 * 상한이 없으면 2MiB 짜리 문서의 글자가 거의 그대로 config 로 흘러 들어가 저장이 413 으로
 * 실패한다(위험 R6 와 같은 부류이며, 다른 축이다).
 *
 * 256 인 이유: 도면의 이름표는 "회의실 A" · "3층 기계실" 처럼 짧고, 그 열 배 이상을 남겨도
 * 문구만의 최악이 경로 쪽 최악과 같은 자리에 선다(요소 상한 64 시절 실측: 57,400 B · 21.90%
 * 대 50,424 B · 19.24%). **넘으면 자르고 보고한다** — 이름표 하나 때문에 문서 전체를
 * 거절하는 것은 대가가 크다.
 *
 * **요소 상한이 1024 가 된 뒤 이 축의 무게가 달라졌다.** 두 최악은 여전히 같은 자리지만
 * (문구 919,470 B · 350.75% 대 경로 807,854 B · 308.17%), 이제 **둘 다 예산을 세 배 넘긴다**.
 * 특히 문구는 명령을 한 칸도 쓰지 않으므로 `MAX_IMPORT_COMMANDS` 아래를 그대로 지나간다 —
 * 위에 적은 413 이 실제로 터지는 가장 짧은 길이 이 축이다. 섞은 최악은 1,578,590 B(602.18%
 * — `MAX_IMPORT_COMMANDS` 머리말의 실측표).
 *
 * 그런데도 이 수를 여기서 더 죄지 않는 것은, 죄어도 예산이 지켜지지 않기 때문이다 — 글자를
 * 반으로 줄여도 문구 1024 짜리 문서는 여전히 예산을 넘는다. 막아야 할 것은 글자 길이가
 * 아니라 **총 바이트**이며 그것은 따로 지어야 한다(요소 상한 머리말). 그때까지 남은 것은
 * **화면이 놓기 전에 그 크기를 말한다**는 사실뿐이다: 추정이 UTF-8 바이트를 세므로
 * (`estimateBytes`) 사용자는 "약 1,542KB" 를 읽고 스스로 물러설 수 있다.
 */
export const MAX_IMPORT_TEXT_LENGTH = 256;

/**
 * `<use>` 전개의 깊이 상한.
 *
 * 순환 검출과 **둘 다** 둔다 — 순환이 아닌 깊은 사슬(도구가 낸 중첩 심볼)도 멈춰야 하고,
 * 깊이 상한만으로는 상한 안에서 도는 순환의 비용이 지수로 커진다.
 */
export const MAX_USE_DEPTH = 4;

/**
 * 호 한 조각의 최대 중심각(라디안).
 *
 * `k = (4/3)·tan(δ/4)` 에서 `δ = π/2` 일 때 최대 반경 오차가 `0.027% × max(rx, ry)` 다.
 * **45° 로 더 잘게 자르는 안을 기각한다** — 오차는 대략 `δ⁶` 로 줄어 1/64 이 되지만
 * **명령 수가 두 배**가 되고 그 수는 `MAX_PATH_COMMANDS` 라는 죔쇠를 직접 먹는다.
 * 90° 의 오차가 이미 평탄화 허용 오차(`FLATTEN_TOLERANCE_PX`)의 1/34 이므로 살 이유가 없다
 * (불변식 K5).
 */
export const ARC_SEGMENT_MAX_RAD = Math.PI / 2;

