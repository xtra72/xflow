// 스테이지 격자 컨텍스트 — 표면이 **그리는 영역을 맞춘 칸**을 오버레이에 알린다
// (SPEC-CANVAS-002 0.9.0 · 사용 시험 "격자가 일정하지 않음" 세 번째 회차).
//
// ## 왜 컨텍스트인가
//
// 그리는 영역은 격자 칸의 정수배여야 한다(`canvasGeometry.stageLattice`). 그래야 선이
// 정수 px 에서 시작해 두 장치 픽셀에 걸치지 않는다. 그런데 그 칸을 정하는 값(격자 간격)은
// **사용자가 편집 도크에서 고르고**, 상자를 짓는 것은 **표면**이다. 둘 사이에는
// `CanvasPanel` 이 있는데 그 파일은 오버레이 슬롯이 주는 값 가운데 둘(투영 · 글자 폭)만
// 골라 넘긴다 — 슬롯에 값을 하나 더 얹어도 오버레이까지 닿지 않는다. 그래서 표면이
// **제 슬롯 둘레에 직접** 이 컨텍스트를 편다. 도크 자리(`canvasEditDockHost`)를 아래로
// 내린 것과 같은 방향의 해법이다: 상태를 위로 올리는 대신 필요한 것만 아래로 내린다.
//
// ## 왜 상태의 주인이 표면인가
//
// 간격은 화면에서 "격자 간격" 으로 읽히지만 코드에서 하는 일은 **그리는 영역의 양자를
// 고르는 것**이고, 그 영역은 표면의 것이다. 오버레이가 들고 있으면 상자를 짓는 쪽이 남의
// 상태를 되물어야 하고, 그 되묻는 자리가 곧 두 번째 출처가 된다(위험 R1).
//
// 값이 `null` 이면 표면 밖이라는 뜻이다(오버레이만 세운 단위 시험이 그렇다). 그때 오버레이는
// 제 지역 상태로 떨어지고 칸도 같은 순수 함수로 직접 구한다 — `useCanvasEditSelection` 이
// provider 없이도 도는 것과 같은 규율이다.
//
// **이 파일은 컴포넌트를 하나도 내보내지 않는다.** 컨텍스트 객체와 훅만 있으므로
// `react-refresh/only-export-components` 가 울지 않는다(`canvasEditDockHost.ts` 와 같은 규율).
//
// @spec SPEC-CANVAS-002 REQ-04

import { createContext, useContext } from 'react';

import type { StageCell, StageSize } from './canvasGeometry';

/** 표면이 그리는 영역을 맞춘 격자 한 벌. */
export interface CanvasStageGrid {
  /** 격자 간격(정수 캔버스 단위). 그리기 · 붙임 · Shift+방향키가 함께 쓰는 그 한 값이다. */
  step: number;
  /** 간격을 바꾼다. 표면은 그리는 영역을 새 칸에 다시 맞춘다. */
  setStep: (step: number) => void;
  /**
   * **보기 배율**(분수). 편집기가 작업 영역을 보여 주는 축척이며 화면은 이것을 백분율
   * 정수로 말한다(SPEC-CANVAS-006 M9 · REQ-09).
   *
   * `step`/`setStep` 과 **같은 짝이고 같은 근거**다 — 배율은 그리는 상자를 정하고 그 상자는
   * 표면의 것이므로, 상태를 상자 짓는 쪽이 들어야 한다. 오버레이가 들고 있으면 상자를
   * 짓는 쪽이 남의 상태를 되물어야 하고 그 되묻는 자리가 곧 두 번째 출처다(위험 R1 ·
   * 불변식 I10).
   *
   * **저장되지 않는다**(가정 A21). 격자 간격과 같은 자리·같은 규율이며, 다이얼로그를 닫으면
   * 기본값으로 돌아간다 — 돌아가는 값이 오늘 사용자가 보던 그 화면이라 잃음이 아니라
   * 되돌아옴이다.
   */
  zoom: number;
  /** 배율을 바꾼다. 표면은 그 배율로 줄인 상자에 격자를 다시 맞춘다. */
  setZoom: (zoom: number) => void;
  /** 한 칸의 CSS px — 표면이 영역을 맞출 때 쓴 **그 값 그대로**다(다시 나누지 않는다). */
  cell: StageCell;
  /**
   * **패널 출력 영역이 작업 영역 안에서 앉는 정수 px 자리** = 캔버스 좌표 `(0,0)` 의 자리
   * (SPEC-CANVAS-006 M3).
   *
   * 격자가 이 값에 앉아야 하는 이유가 이 칸이 존재하는 이유 전부다. 붙임(`snapDelta`)은
   * 캔버스 단위로 `k × step` 에 죄므로 그 자리는 화면에서 `origin + k × cell` 이다. 격자를
   * **작업 영역**의 왼쪽 위에 앉히면 선은 `0 + k × cell` 에 서고, 둘이 만나려면 `origin` 이
   * `cell` 의 배수여야 하는데 그럴 이유가 없다 — 여백이 한 칸의 배수가 아닌 순간 **그린
   * 선과 붙은 자리가 갈라진다**. 이 저장소가 세 번(0.8.0 · 0.9.0 · 0.10.0) 걷어낸 그
   * 거짓말이 모양만 바꿔 돌아오는 자리이며, 그래서 자리를 오버레이가 다시 파생하지 않고
   * **상자를 지은 쪽이 내려보낸다**(위험 R1 · R3).
   *
   * 편집이 꺼져 있으면 `(0,0)` 이다 — 두 상자가 겹쳐 오늘과 같은 그림이 된다.
   */
  origin: StageCell;
  /**
   * **작업 영역(캔버스 비트맵이 덮는 상자)의 CSS px 크기**(SPEC-CANVAS-006 M3).
   *
   * 격자는 출력 영역이 아니라 이 상자 전체에 그려진다 — 저술 여백에도 칸이 보여야 밖에
   * 놓은 요소가 어디에 붙는지 눈으로 읽힌다(REQ-04). 위 `origin` 과 짝이며, 편집이 꺼져
   * 있으면 출력 영역과 같은 크기다.
   */
  box: StageSize;
}

export const CanvasStageGridContext = createContext<CanvasStageGrid | null>(null);

/**
 * 표면이 편 격자 한 벌. **표면 밖에서는 `null` 이다.**
 *
 * `null` 을 숨기지 않는 것에 뜻이 있다 — 표면이 없으면 맞출 영역도 없으므로, 받는 쪽이
 * 그 사실을 알고 제 값으로 폴백해야 한다. 006 이 더한 두 칸의 폴백도 같은 규율을 따른다:
 * 표면이 없으면 작업 영역도 없으므로 `origin = {0,0}` · `box = projection.stage` 로
 * 떨어진다 — 그것이 곧 "상자가 하나뿐이던 시절" 의 값이며 006 이전과 같다. 배율도 같다:
 * 표면이 없으면 지역 상태로 떨어지고 기본값은 `DEFAULT_WORKSPACE_ZOOM` 이다.
 */
export function useCanvasStageGrid(): CanvasStageGrid | null {
  return useContext(CanvasStageGridContext);
}
