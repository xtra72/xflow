// 임의 앵커의 자료형과 그 격자 (SPEC-CANVAS-011 M3').
//
// 고정 아홉(M3)은 **저장하지 않는다**(A1) — 윤곽 상자에서 파생한다. 임의 앵커는 그 반대다
// (A10): 사용자가 고른 자리이므로 파생시킬 근거가 없고, 저장하지 않으면 다시 찾을 길이
// 없다. 그래서 이 파일에만 저장되는 앵커의 형상이 적힌다.
//
// ## 왜 `anchors.ts` 가 아니라 여기인가
//
// `canvasConfig` 가 `CustomAnchor` 를 필드 타입으로 들어야 하는데, `anchors.ts` 는
// `canvasGeometry` → `group/groupTypes` → `canvasConfig` 를 지나 도로 `canvasConfig` 에
// 닿는다. 자료형만 잎 모듈로 떼어 두면 그 고리가 생기지 않는다 — `shapes/pathTypes` 밖에
// 들이지 않는 것이 이 파일의 형상이다.
//
// **이 모듈은 DOM 도 산술도 모른다.** 자료형 하나와 상수 둘뿐이다.
//
// @spec SPEC-CANVAS-011 REQ-02'

import { PATH_LOCAL_EXTENT } from '../shapes/pathTypes';

/**
 * 임의 앵커가 사는 요소 로컬 정수 격자. 요소 상자 한 변이 이 값에 대응한다.
 *
 * **값을 베끼지 않고 008 의 경로 격자에서 파생시킨다.** 004 가 `GROUP_LOCAL_EXTENT` 에서
 * 쓴 그 근거를 그대로 쓴다 — 세 격자는 같은 개념("상자 하나의 로컬 정수 격자")이고, 값을
 * 따로 적으면 언젠가 한쪽만 바뀐다. 그래서 이 줄에 숫자 리터럴이 **없는 것**이 요구다.
 *
 * 이 격자가 경로 명령의 격자와 **같은 값**이라는 사실이 꼭지점 붙임(REQ-02'-b)의 전부다.
 * 다르면 저장 좌표와 경로 명령 좌표를 견주기 전에 환산이 한 번 끼어들고, 그 환산의
 * 반올림이 "정확히 같다" 를 표현 불가능하게 만든다.
 */
export const ANCHOR_LOCAL_EXTENT = PATH_LOCAL_EXTENT;

/**
 * 꼭지점에 붙는 허용 오차(로컬 격자 단위).
 *
 * **상자 한 변의 비율로 적는다.** 절대 px 로 두면 같은 손놀림이 작은 도형에서는 과하게
 * 붙고 큰 도형에서는 닿지 않는다 — 로컬 격자는 도형과 함께 늘어나므로, 비율로 두면 화면에
 * 보이는 여유가 도형 크기에 비례해 따라온다. 1/50 은 한 변의 2% 다.
 */
export const ANCHOR_SNAP_LOCAL = ANCHOR_LOCAL_EXTENT / 50;

/**
 * 임의 앵커 하나. 좌표는 **요소 로컬 정수 격자**(공칭 0..`ANCHOR_LOCAL_EXTENT`)다.
 *
 * 로컬이라서 크기 변경이 **코드 한 줄 없이** 따라온다(A10) — 8핸들이 상자를 바꾸면
 * 저장 좌표는 한 자리도 바뀌지 않고 캔버스 자리만 새 상자에서 다시 나온다. 절대 좌표로
 * 두었다면 크기 조절마다 앵커를 함께 옮기는 코드가 필요하고, 그 코드를 빠뜨린 경로가
 * 하나라도 생기면 앵커가 옛 자리에 남는다.
 *
 * `id` 는 **요소 안에서** 유일하다. 연결선이 `{ el, a }` 로 가리키므로 요소를 건너서까지
 * 유일할 필요가 없다.
 */
export interface CustomAnchor {
  id: string;
  x: number;
  y: number;
}
